export function tr(lang: Lang, key: string, vars?: Record<string, string | number>): string {
  const base = dictionaries[lang]?.[key] ?? dictionaries.en[key] ?? key;
  if (!vars) return base;
  return base.replace(/\{(\w+)\}/g, (_m, name) => String(vars[name] ?? `{${name}}`));
}
